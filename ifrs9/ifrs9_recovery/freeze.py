"""Release freeze: copy the analysis-ready outputs into releases/<release_id>/ with a hash manifest.

The release records the code commit that generated the outputs (release_stats.json git_commit) and refuses to
freeze if that commit is not HEAD, if the working tree has uncommitted changes to code or data, or if the last
test run failed. The summary inside the release is the generated one; nothing is edited here.
"""
from __future__ import annotations

import shutil
import subprocess

from . import config as C
from .util import read_json, sha256_file, utcnow, write_json

FILES = {  # release path -> source
    "verified_panel.csv": C.DATA / "verified_panel.csv",
    "field_status.csv": C.DATA / "field_status.csv",
    "outcome_eligibility.csv": C.DATA / "outcome_eligibility.csv",
    "row_versions.csv": C.DATA / "row_versions.csv",
    "version_decisions.csv": C.DATA / "review" / "version_decisions.csv",
    "version_reconciliations.csv": C.DATA / "review" / "version_reconciliations.csv",
    "eligibility_rules.csv": C.DATA / "review" / "eligibility_rules.csv",
    "conflicts.csv": C.DATA / "conflicts.csv",
    "reviewer_conflicts.csv": C.DATA / "review" / "reviewer_conflicts.csv",
    "exceptions_register.csv": C.DATA / "exceptions_register.csv",
    "exception_investigations.md": C.DATA / "review" / "exception_investigations.md",
    "denominator_compatibility.csv": C.DATA / "denominator_compatibility.csv",
    "going_concern_reviews.csv": C.DATA / "review" / "going_concern_reviews.csv",
    "unresolved_gaps.csv": C.DATA / "unresolved_gaps.csv",
    "evidence_long.csv": C.DATA / "evidence_long.csv",
    "change_register.csv": C.DATA / "change_register.csv",
    "IFRS9_Verified_Master.xlsx": C.OUTPUTS / "IFRS9_Verified_Master.xlsx",
    "release_stats.json": C.OUTPUTS / "release_stats.json",
    "reconciliation_summary.md": C.OUTPUTS / "reconciliation_summary.md",
    "test_results.json": C.OUTPUTS / "test_results.json",
    "release_manifest.json": C.OUTPUTS / "release_manifest.json",
    "research_data_handoff.zip": C.OUTPUTS / "research_data_handoff.zip",
}


def _git(*a) -> str:
    return subprocess.run(["git", *a], cwd=C.ROOT, capture_output=True, text=True).stdout.strip()


def run(release_id: str) -> dict:
    stats = read_json(C.OUTPUTS / "release_stats.json", {})
    tests = read_json(C.OUTPUTS / "test_results.json", {})
    head = _git("rev-parse", "HEAD")
    if stats.get("git_commit") != head:
        raise SystemExit(f"release_stats commit {stats.get('git_commit')} != HEAD {head}: commit, then re-export")
    dirty = [l for l in _git("status", "--porcelain", "--", "ifrs9_recovery", "tests", "data").splitlines() if l.strip()]
    if dirty:
        raise SystemExit(f"uncommitted code/data changes: {dirty[:5]}")
    if tests.get("exit_status") != 0:
        raise SystemExit("last test run did not pass")
    dest = C.ROOT / "releases" / release_id
    dest.mkdir(parents=True, exist_ok=True)
    files = dict(FILES)
    for p in sorted((C.OUTPUTS / "analysis").glob("*.csv")):
        files[f"analysis/{p.name}"] = p
    for p in sorted((C.OUTPUTS / "readiness").glob("*")):
        files[f"readiness/{p.name}"] = p
    out = {}
    for rel, src in files.items():
        t = dest / rel
        t.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, t)
        out[rel] = {"sha256": sha256_file(t), "bytes": t.stat().st_size, "source": str(src.relative_to(C.ROOT))}
    manifest = {"release_id": release_id, "frozen_utc": utcnow(), "code_commit": head, "branch": _git("rev-parse", "--abbrev-ref", "HEAD"),
                "panel_rows": stats["panel"]["rows"], "tests": tests.get("suites", {}), "files": out,
                "note": "Outputs generated by the code at code_commit; this folder is added in a later commit. Thesis not updated."}
    write_json(dest / "RELEASE_MANIFEST.json", manifest)
    return {"release": str(dest.relative_to(C.ROOT)), "files": len(out), "code_commit": head}
